"""Deterministic synthetic CV fixture dataset (T129).

The images are generated, not collected: no patient data is involved. Blob
positions come from a fixed seed, so :func:`build_dataset` writes byte-identical
PNGs and a byte-identical ``labels.json`` on every run. That is what the
determinism test compares against the committed fixtures.

Provenance (dataset name, version, licence, hash, generator) is embedded in
``labels.json`` and repeated in the evaluation report.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

import numpy as np
from PIL import Image

DATASET_NAME = "enamel-cv-fixture"
DATASET_VERSION = "1.0.0"
DATASET_SEED = 7
LICENCE = "Project-internal synthetic fixture data; contains no patient data."
GENERATOR = "ml/cv/fixtures.py"
IMAGE_SIZE = 48
IMAGE_COUNT = 12
TARGET_LABEL = "radiopacity"

#: Every third image is a negative (no finding) so both classes are present.
NEGATIVE_EVERY = 3


def canonical_json(payload: Any) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), default=str)


def _image(index: int, positive: bool, rng: np.random.RandomState) -> np.ndarray:
    size = IMAGE_SIZE
    ys, xs = np.mgrid[0:size, 0:size]
    background = 20.0 + (index % 4) * 3.0
    frame = np.full((size, size), background, dtype=np.float64)

    if positive:
        center_x = int(rng.randint(size // 4, size - size // 4))
        center_y = int(rng.randint(size // 4, size - size // 4))
        amplitude = 180.0 + (index % 5) * 12.0
        radius_sq = (xs - center_x) ** 2 + (ys - center_y) ** 2
        frame += amplitude * np.exp(-radius_sq / (2 * (size / 10) ** 2))

    return np.clip(frame, 0, 255).astype(np.uint8)


def build_dataset(out_dir: Path) -> dict[str, Any]:
    """Write the fixture images + labels and return a manifest."""

    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.RandomState(DATASET_SEED)

    items: list[dict[str, Any]] = []
    for index in range(IMAGE_COUNT):
        positive = index % NEGATIVE_EVERY != 0
        array = _image(index, positive, rng)
        name = f"img_{index:03d}.png"
        Image.fromarray(array, mode="L").save(out_dir / name)
        findings = []
        if positive:
            findings = [{"label": TARGET_LABEL, "bbox": None}]
        items.append({"image": name, "label": 1 if positive else 0, "findings": findings})

    dataset = {
        "name": DATASET_NAME,
        "version": DATASET_VERSION,
        "licence": LICENCE,
        "generator": GENERATOR,
        "seed": DATASET_SEED,
        "target_label": TARGET_LABEL,
        "image_size": IMAGE_SIZE,
        "items": items,
    }
    dataset["hash"] = hashlib.sha256(canonical_json(dataset).encode("utf-8")).hexdigest()

    (out_dir / "labels.json").write_text(
        json.dumps(dataset, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    (out_dir / "README.md").write_text(readme_text(dataset), encoding="utf-8")

    return {
        "dir": str(out_dir),
        "dataset": dataset,
        "images": [item["image"] for item in items],
        "hash": dataset["hash"],
    }


def readme_text(dataset: dict[str, Any]) -> str:
    return "\n".join(
        [
            "# CV fixture dataset",
            "",
            f"Generated by `{GENERATOR}` (`build_dataset`).",
            "",
            "## Provenance",
            "",
            f"- Dataset: `{dataset['name']}` version `{dataset['version']}`",
            f"- Licence: {dataset['licence']}",
            f"- Generator: `{dataset['generator']}` (seed {dataset['seed']})",
            f"- Hash: `{dataset['hash']}`",
            f"- Images: {len(dataset['items'])} synthetic {dataset['image_size']}x"
            f"{dataset['image_size']} grayscale PNGs",
            "",
            "## Notes",
            "",
            "- The images are synthetic: no real patient data is present.",
            "- The labels describe the presence of a synthetic bright blob only.",
            "- This dataset is for pipeline and evaluation wiring, not for measuring",
            "  clinical accuracy. See the evaluation report's limitations section.",
            "",
        ]
    )


def load_dataset(data_dir: Path) -> dict[str, Any]:
    """Read ``labels.json`` from ``data_dir``."""

    return json.loads((data_dir / "labels.json").read_text(encoding="utf-8"))


def dataset_hash(dataset: dict[str, Any]) -> str:
    """Recompute the dataset hash (the stored ``hash`` key is excluded)."""

    payload = {key: value for key, value in dataset.items() if key != "hash"}
    return hashlib.sha256(canonical_json(payload).encode("utf-8")).hexdigest()


