"""Export the OpenAPI schema to a deterministic JSON file.

The schema is generated by drf-spectacular and written with sorted keys and a
trailing newline, so repeated runs produce byte-identical output. The frontend
Orval pipeline consumes this file directly.
"""

from __future__ import annotations

import json
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand, CommandError
from drf_spectacular.generators import SchemaGenerator


class Command(BaseCommand):
    help = "Write the OpenAPI schema as deterministic JSON."

    def add_arguments(self, parser):
        parser.add_argument(
            "--out",
            default="openapi/schema.json",
            help="Output path (absolute, or relative to the backend directory).",
        )

    def handle(self, *args, **options):
        out = Path(options["out"])
        if not out.is_absolute():
            out = Path(settings.BASE_DIR) / out

        try:
            generator = SchemaGenerator()
            schema = generator.get_schema(request=None, public=True)
        except Exception as exc:  # pragma: no cover - defensive CLI boundary
            raise CommandError(f"OpenAPI generation failed: {exc}") from exc

        out.parent.mkdir(parents=True, exist_ok=True)
        text = json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        out.write_text(text, encoding="utf-8")
        self.stdout.write(f"Wrote OpenAPI schema to {out}")
