"""Patient export as JSON or PDF (T106).

Export is a read of one patient in one clinic. It never touches another tenant,
never writes to the filesystem (the PDF is returned as bytes) and caps the
related rows it will emit at :data:`MAX_EXPORT_ROWS`, reporting ``truncated``
when the cap is hit.

The PDF is explicitly labelled as an export/synthetic document: it carries a
banner, the generating clinic and a "not a certified medical record" note, so a
downloaded file cannot be mistaken for an official record.
"""

from __future__ import annotations

from datetime import datetime
from io import BytesIO
from typing import Any

from django.utils import timezone

from ..models import Allergy, Encounter, MedicalHistory, Patient
from .history import patient_allergies, patient_medical_history

MAX_EXPORT_ROWS = 5000
EXPORT_BANNER = "ENAMEL CLINICAL RECORD EXPORT"
EXPORT_NOTICE = (
    "Export generated by Enamel. This is a synthetic/export document and is not "
    "a certified medical record."
)


def _encounters(patient: Patient, limit: int) -> list[Encounter]:
    if limit <= 0:
        return []
    return list(
        Encounter.objects.filter(patient=patient).order_by("-occurred_at", "-id")[:limit]
    )


def build_patient_export(patient: Patient) -> tuple[dict[str, Any], int]:
    """Return ``(payload, row_count)`` for the JSON export."""

    remaining = MAX_EXPORT_ROWS
    allergies = patient_allergies(patient)[:remaining]
    remaining -= len(allergies)
    history = patient_medical_history(patient)[:remaining]
    remaining -= len(history)
    encounters = _encounters(patient, remaining)

    row_count = len(allergies) + len(history) + len(encounters)
    truncated = remaining <= 0 and _has_more(patient, allergies, history, encounters)
    payload = {
        "export": {
            "format": "json",
            "generated_at": timezone.now().isoformat(),
            "rows": row_count,
            "truncated": truncated,
            "notice": EXPORT_NOTICE,
        },
        "clinic": {
            "id": str(patient.clinic_id),
        },
        "patient": {
            "id": str(patient.id),
            "number": patient.number,
            "first_name": patient.first_name,
            "last_name": patient.last_name,
            "preferred_name": patient.preferred_name,
            "full_name": patient.full_name,
            "date_of_birth": patient.date_of_birth.isoformat()
            if patient.date_of_birth
            else None,
            "sex_at_birth": patient.sex_at_birth,
            "gender_identity": patient.gender_identity,
            "phone_e164": patient.phone_e164,
            "email": patient.email,
            "address_json": patient.address_json,
            "language": patient.language,
            "preferred_contact": patient.preferred_contact,
            "status": patient.status,
            "source": patient.source,
            "notes": patient.notes,
            "created_at": patient.created_at.isoformat(),
            "updated_at": patient.updated_at.isoformat(),
        },
        "allergies": [_allergy_payload(row) for row in allergies],
        "medical_history": [_history_payload(row) for row in history],
        "encounters": [_encounter_payload(row) for row in encounters],
    }
    return payload, row_count


def _has_more(
    patient: Patient,
    allergies: list[Allergy],
    history: list[MedicalHistory],
    encounters: list[Encounter],
) -> bool:
    return (
        Allergy.objects.filter(patient=patient).count() > len(allergies)
        or MedicalHistory.objects.filter(patient=patient).count() > len(history)
        or Encounter.objects.filter(patient=patient).count() > len(encounters)
    )


def _allergy_payload(row: Allergy) -> dict[str, Any]:
    return {
        "id": str(row.id),
        "substance": row.substance,
        "reaction": row.reaction,
        "severity": row.severity,
        "is_active": row.is_active,
        "recorded_at": row.recorded_at.isoformat(),
    }


def _history_payload(row: MedicalHistory) -> dict[str, Any]:
    return {
        "id": str(row.id),
        "kind": row.kind,
        "label": row.label,
        "since": row.since.isoformat() if row.since else None,
        "notes": row.notes,
        "is_active": row.is_active,
    }


def _encounter_payload(row: Encounter) -> dict[str, Any]:
    return {
        "id": str(row.id),
        "kind": row.kind,
        "occurred_at": row.occurred_at.isoformat(),
        "chief_complaint": row.chief_complaint,
        "notes": row.notes,
        "diagnosis_codes": list(row.diagnosis_codes or []),
        "status": row.status,
        "version": row.version,
        "appointment_id": str(row.appointment_id) if row.appointment_id else None,
    }


def _pdf_story(payload: dict[str, Any]) -> list[Any]:
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, Spacer, Table, TableStyle

    styles = getSampleStyleSheet()
    patient = payload["patient"]
    generated = datetime.fromisoformat(payload["export"]["generated_at"])

    story: list[Any] = [
        Paragraph(EXPORT_BANNER, styles["Title"]),
        Paragraph(EXPORT_NOTICE, styles["Italic"]),
        Spacer(1, 12),
        Paragraph(
            f"Clinic: {payload['clinic']['id']} &nbsp;&nbsp; "
            f"Generated: {generated:%Y-%m-%d %H:%M %Z}",
            styles["Normal"],
        ),
        Spacer(1, 12),
        Paragraph("Patient", styles["Heading2"]),
    ]

    rows = [
        ["Number", patient["number"]],
        ["Name", patient["full_name"]],
        ["Date of birth", patient["date_of_birth"] or "-"],
        ["Sex at birth", patient["sex_at_birth"]],
        ["Phone", patient["phone_e164"] or "-"],
        ["Email", patient["email"] or "-"],
        ["Status", patient["status"]],
        ["Source", patient["source"]],
    ]
    story.append(Table(rows, style=TableStyle([("GRID", (0, 0), (-1, -1), 0.25, None)])))

    story.append(Spacer(1, 12))
    story.append(Paragraph("Allergies", styles["Heading2"]))
    if payload["allergies"]:
        allergy_rows = [["Severity", "Active", "Substance"]]
        allergy_rows += [
            [row["severity"], "yes" if row["is_active"] else "no", row["substance"]]
            for row in payload["allergies"]
        ]
        story.append(
            Table(allergy_rows, style=TableStyle([("GRID", (0, 0), (-1, -1), 0.25, None)]))
        )
    else:
        story.append(Paragraph("None recorded.", styles["Normal"]))

    story.append(Spacer(1, 12))
    story.append(Paragraph("Medical history", styles["Heading2"]))
    if payload["medical_history"]:
        history_rows = [["Kind", "Active", "Label"]]
        history_rows += [
            [row["kind"], "yes" if row["is_active"] else "no", row["label"]]
            for row in payload["medical_history"]
        ]
        story.append(
            Table(history_rows, style=TableStyle([("GRID", (0, 0), (-1, -1), 0.25, None)]))
        )
    else:
        story.append(Paragraph("None recorded.", styles["Normal"]))

    story.append(Spacer(1, 12))
    story.append(Paragraph("Encounters", styles["Heading2"]))
    if payload["encounters"]:
        encounter_rows = [["Occurred", "Kind", "Status"]]
        encounter_rows += [
            [row["occurred_at"][:19].replace("T", " "), row["kind"], row["status"]]
            for row in payload["encounters"]
        ]
        story.append(
            Table(
                encounter_rows,
                style=TableStyle([("GRID", (0, 0), (-1, -1), 0.25, None)]),
            )
        )
    else:
        story.append(Paragraph("None recorded.", styles["Normal"]))

    story.append(Spacer(1, 12))
    story.append(
        Paragraph(
            f"Rows: {payload['export']['rows']}"
            + (" (truncated)" if payload["export"]["truncated"] else ""),
            styles["Normal"],
        )
    )
    return story


def build_patient_export_pdf(patient: Patient) -> tuple[bytes, int]:
    """Return ``(pdf_bytes, row_count)`` for the PDF export."""

    from reportlab.lib.pagesizes import A4
    from reportlab.platypus import SimpleDocTemplate

    payload, row_count = build_patient_export(patient)
    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        title=f"Enamel export {patient.number}",
        author="Enamel",
        subject=EXPORT_BANNER,
    )
    document.build(_pdf_story(payload))
    return buffer.getvalue(), row_count


__all__ = [
    "EXPORT_BANNER",
    "EXPORT_NOTICE",
    "MAX_EXPORT_ROWS",
    "build_patient_export",
    "build_patient_export_pdf",
]
